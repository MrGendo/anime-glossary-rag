squash = lambda s: re.sub(r"\s+", "", s)
anchor_fail = []
for s in S:
    ev_squashed = squash(" ".join(by_cid[cid] for cid in s["evidence_chunk_ids"]))
    for fact in s["required_facts"]:
        runs = re.findall(r"[\u3040-\u30ff\u4e00-\u9fff]{6,}", fact)
        if runs and not any(squash(r) in ev_squashed for r in runs):
            anchor_fail.append((s["question_id"], runs[0][:26]))
